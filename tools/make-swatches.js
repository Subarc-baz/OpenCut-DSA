#!/usr/bin/env node
// Same as make-swatches.py, for machines with Node. Usage: node tools/make-swatches.js
const fs = require('fs'), path = require('path');
const src = path.resolve(__dirname, '..', 'swatches');
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.svg': 'image/svg+xml' };
const items = []; let total = 0;
(function walk(d) {
  fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1)).forEach(e => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) return walk(p);
    const ext = path.extname(e.name).toLowerCase(); if (!MIME[ext]) return;
    const rel = path.relative(src, p).split(path.sep).join('/'), b = fs.readFileSync(p);
    if (b.length > 8 * 1024 * 1024) { console.error('SKIPPED (over 8 MB): ' + rel); return; }
    total += b.length; items.push({ id: rel, name: rel.slice(0, rel.length - ext.length), data: 'data:' + MIME[ext] + ';base64,' + b.toString('base64') });
  });
})(src);
items.sort((a, b) => { const x = a.id.toLowerCase(), y = b.id.toLowerCase(); return x < y ? -1 : x > y ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0; });
fs.writeFileSync(path.join(src, 'swatches.js'), '/* generated by tools/make-swatches - do not edit */\nwindow.SWATCH_LIB=' + JSON.stringify(items) + ';\n');
console.log(items.length + ' swatch(es), ' + (total / 1048576).toFixed(1) + ' MB of images -> swatches/swatches.js');
