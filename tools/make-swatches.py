#!/usr/bin/env python3
"""Packs the images in ./swatches into swatches/swatches.js, which index.html loads at start-up.
Usage:  python3 tools/make-swatches.py     (then reload the app)
Supported: .png .jpg .jpeg .gif .webp .svg (SVGs need width/height). Sub-folders are searched; the id is the relative path."""
import base64, json, os, sys
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
src = os.path.join(root, 'swatches')
MIME = {'.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.svg': 'image/svg+xml'}
MAX = 8 * 1024 * 1024
items, total = [], 0
for dp, dn, fn in os.walk(src):
    dn.sort()
    for f in sorted(fn):
        ext = os.path.splitext(f)[1].lower()
        if ext not in MIME: continue
        p = os.path.join(dp, f); rel = os.path.relpath(p, src).replace(os.sep, '/')
        b = open(p, 'rb').read()
        if len(b) > MAX: print('SKIPPED (over 8 MB): ' + rel, file=sys.stderr); continue
        total += len(b)
        items.append({'id': rel, 'name': os.path.splitext(rel)[0], 'data': 'data:%s;base64,%s' % (MIME[ext], base64.b64encode(b).decode('ascii'))})
items.sort(key=lambda i: (i['id'].lower(), i['id']))
out = '/* generated by tools/make-swatches - do not edit */\nwindow.SWATCH_LIB=' + json.dumps(items, ensure_ascii=True, separators=(',', ':')) + ';\n'
open(os.path.join(src, 'swatches.js'), 'w', newline='\n').write(out)
print('%d swatch(es), %.1f MB of images -> swatches/swatches.js' % (len(items), total / 1048576))
if total > 40 * 1024 * 1024: print('Warning: large library; the app may start slowly.', file=sys.stderr)
