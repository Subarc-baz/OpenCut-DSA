/* v6.2 Swatch library + Bucket tool.
   Library data comes from swatches/swatches.js (generated by tools/make-swatches.py|js from the images in swatches/).
   A filled object carries  o.pattern = {sid, size}  (sid = library id, size = tile width in inches) and keeps o.fill as the
   swatch's average colour, so every v4/v5 code path that only knows `fill` keeps working. */
(function () {
  'use strict';
  var LIB = (window.SWATCH_LIB || []).filter(function (s) { return s && typeof s.id === 'string' && /^data:image\//.test(s.data || ''); });
  var byId = {}, state = { sid: null, size: 1 };
  window.__toolHandlers = window.__toolHandlers || {};

  var EXT = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp', svg: 'image/svg+xml' }, MAXBYTES = 8 * 1024 * 1024;
  function prep(s) {
    var im = new Image(); s.img = im; s.avg = s.avg || '#888888'; byId[s.id] = s;
    im.onload = function () {
      try { var c = document.createElement('canvas'); c.width = c.height = 1; var x = c.getContext('2d'); x.drawImage(im, 0, 0, 1, 1); var d = x.getImageData(0, 0, 1, 1).data; s.avg = '#' + [d[0], d[1], d[2]].map(function (v) { return ('0' + v.toString(16)).slice(-2); }).join(''); } catch (e) { }
      if (typeof ctx !== 'undefined' && ctx) draw(); renderPanel();
    };
    im.src = s.data;
  }
  LIB.forEach(prep);
  function sortLib() { LIB.sort(function (a, b) { return (a.user ? 1 : 0) - (b.user ? 1 : 0) || (a.id.toLowerCase() < b.id.toLowerCase() ? -1 : a.id.toLowerCase() > b.id.toLowerCase() ? 1 : 0); }); }

  /* ---------- user-added swatches: stored in this browser (IndexedDB), so they are remembered between sessions ---------- */
  var idb = null, persistOK = true;
  function db() {
    if (idb) return idb;
    idb = new Promise(function (res, rej) {
      try { var rq = indexedDB.open('opencut-dsa-swatches', 1); rq.onupgradeneeded = function () { rq.result.createObjectStore('swatches', { keyPath: 'id' }); }; rq.onsuccess = function () { res(rq.result); }; rq.onerror = function () { rej(rq.error); }; } catch (e) { rej(e); }
    });
    return idb;
  }
  function tx(mode, fn) { return db().then(function (d) { return new Promise(function (res, rej) { var t = d.transaction('swatches', mode), st = t.objectStore('swatches'), r = fn(st); t.oncomplete = function () { res(r && r.result); }; t.onerror = t.onabort = function () { rej(t.error); }; }); }); }
  function persist(item) { return tx('readwrite', function (st) { return st.put({ id: item.id, name: item.name, data: item.data }); }).catch(function () { persistOK = false; }); }
  function unpersist(id) { return tx('readwrite', function (st) { return st.delete(id); }).catch(function () { }); }
  function restoreUser() {
    return tx('readonly', function (st) { return st.getAll(); }).then(function (rows) {
      (rows || []).forEach(function (r) { if (r && /^user\//.test(r.id) && /^data:image\//.test(r.data || '') && !byId[r.id]) { var it = { id: r.id, name: r.name || r.id.slice(5), data: r.data, user: true }; LIB.push(it); prep(it); } });
      sortLib(); renderPanel();
    }).catch(function () { persistOK = false; });
  }
  function readAsDataURL(f) { return new Promise(function (res, rej) { var fr = new FileReader(); fr.onload = function () { res(fr.result); }; fr.onerror = function () { rej(fr.error); }; fr.readAsDataURL(f); }); }
  /* items: [{file, rel}] -> adds every valid image; returns {added, skipped:[reasons]} */
  function addFiles(items) {
    var added = 0, skipped = [];
    return items.reduce(function (chain, it) {
      return chain.then(function () {
        var f = it.file, ext = (f.name.split('.').pop() || '').toLowerCase();
        if (!EXT[ext]) { skipped.push(f.name + ': not an image type I can use (png jpg gif webp svg)'); return; }
        if (f.size > MAXBYTES) { skipped.push(f.name + ': over 8 MB'); return; }
        return readAsDataURL(f).then(function (url) {
          var data = url.replace(/^data:[^;,]*/, 'data:' + EXT[ext]), id = 'user/' + (it.rel || f.name), old = byId[id];
          if (old) { var k = LIB.indexOf(old); if (k >= 0) LIB.splice(k, 1); }
          var item = { id: id, name: (it.rel || f.name).replace(/\.[^.]+$/, ''), data: data, user: true }; LIB.push(item); prep(item); added++;
          return persist(item);
        }, function () { skipped.push(f.name + ': could not be read'); });
      });
    }, Promise.resolve()).then(function () { sortLib(); renderPanel(); status(added, skipped); return { added: added, skipped: skipped }; });
  }
  var lastStatus = { text: '', color: '#9a9ab8' };
  function status(added, skipped) {
    lastStatus.text = (added ? 'Added ' + added + ' swatch' + (added === 1 ? '' : 'es') + '. ' : 'Nothing added. ') + (skipped.length ? 'Skipped: ' + skipped.slice(0, 3).join('; ') + (skipped.length > 3 ? ' (+' + (skipped.length - 3) + ' more)' : '') + '. ' : '') + (persistOK ? '' : 'This browser would not save them for next time.');
    lastStatus.color = skipped.length && !added ? '#ff8a8a' : '#9a9ab8'; showStatus();
  }
  function showStatus() { var el = document.getElementById('swStatus'); if (el) { el.textContent = lastStatus.text; el.style.color = lastStatus.color; } }
  function removeSwatch(id) {
    var s = byId[id]; if (!s || !s.user) return false; LIB.splice(LIB.indexOf(s), 1); delete byId[id]; if (state.sid === id) state.sid = null;
    unpersist(id); renderPanel(); if (typeof draw === 'function') draw(); return true;
  }
  /* Choose folder: a standard <input type=file webkitdirectory>, which Brave, Chrome, Edge and Firefox all support (no flags, no permission API). */
  function folderFiles(fileList) {
    var out = [];
    Array.prototype.slice.call(fileList || []).forEach(function (f) {
      var rp = f.webkitRelativePath || f.name, parts = rp.split('/'); if (parts.length > 1) parts.shift();   /* drop the chosen folder's own name */
      if (parts.length > 6 || out.length >= 500) return;
      if (EXT[(f.name.split('.').pop() || '').toLowerCase()]) out.push({ file: f, rel: parts.join('/') });
    });
    return out;
  }
  function chooseFolder() { var fi = document.getElementById('swFolderInput'); if (fi) fi.click(); }

  function ready(s) { return s && s.img && s.img.complete && s.img.naturalWidth > 0; }
  function tileW(p, s) { return Math.max(4, (+p.size || 1) * 96); }

  /* Canvas fill style for an object with a pattern, anchored to the object's top-left; null = use plain fill. */
  window.patFill = function (c, o) {
    var p = o && o.pattern; if (!p) return null; var s = byId[p.sid]; if (!ready(s)) return null;
    var pat = c.createPattern(s.img, 'repeat'); if (!pat) return null;
    var b = (typeof objBounds === 'function') ? objBounds(o) : { x: o.x || 0, y: o.y || 0 }, k = tileW(p, s) / s.img.naturalWidth;
    if (pat.setTransform && typeof DOMMatrix === 'function') pat.setTransform(new DOMMatrix([k, 0, 0, k, b.x, b.y]));
    return pat;
  };

  /* For SVG export: {href, x, y, w, h} in design px, or null. */
  function svgPattern(o) {
    var p = o && o.pattern; if (!p) return null; var s = byId[p.sid]; if (!s) return null;
    var b = (typeof objBounds === 'function') ? objBounds(o) : { x: o.x || 0, y: o.y || 0 }, w = tileW(p, s), nw = s.img && s.img.naturalWidth, nh = s.img && s.img.naturalHeight;
    return { href: s.data, x: b.x, y: b.y, w: w, h: nw ? w * nh / nw : w };
  }

  /* ---------- precise hit test for fill tools: topmost object whose INTERIOR is under the point ---------- */
  function hitShape(pt) {
    ctx.save(); ctx.setTransform(1, 0, 0, 1, 0, 0);
    try {
      for (var i = objects.length - 1; i >= 0; i--) {
        var o = objects[i]; if (o.hidden) continue; var hit = false;
        if (o.type === 'ellipse') { ctx.beginPath(); ctx.ellipse(o.cx, o.cy, o.rx || 1, o.ry || 1, 0, 0, Math.PI * 2); hit = ctx.isPointInPath(pt.x, pt.y); }
        else if (o.type === 'star') { ctx.beginPath(); starPath(ctx, o.cx, o.cy, o.r, o.ir, o.n); hit = ctx.isPointInPath(pt.x, pt.y); }
        else if (o.type === 'polygon') { ctx.beginPath(); polyPath(ctx, o.cx, o.cy, o.r, o.n); hit = ctx.isPointInPath(pt.x, pt.y); }
        else if (o.type === 'path') {
          var fx = o.w / (o.bw || 1), fy = o.h / (o.bh || 1); ctx.beginPath();
          (o.contours || []).forEach(function (ct) { ct.forEach(function (q, j) { var X = o.x + q[0] * fx, Y = o.y + q[1] * fy; if (j) ctx.lineTo(X, Y); else ctx.moveTo(X, Y); }); ctx.closePath(); });
          hit = ctx.isPointInPath(pt.x, pt.y, 'nonzero');
        }
        else if (o.type === 'line') { var dx = o.x2 - o.x1, dy = o.y2 - o.y1, L = Math.hypot(dx, dy) || 1, t = Math.max(0, Math.min(1, ((pt.x - o.x1) * dx + (pt.y - o.y1) * dy) / (L * L))); hit = Math.hypot(pt.x - (o.x1 + t * dx), pt.y - (o.y1 + t * dy)) <= Math.max(6 / zoom, (o.strokeW || 2) / 2); }
        else { var b = objBounds(o); hit = pt.x >= b.x && pt.x <= b.x + b.w && pt.y >= b.y && pt.y <= b.y + b.h; }
        if (hit) return i;
      }
    } finally { ctx.restore(); }
    return -1;
  }
  window.hitShape = hitShape;

  /* ---------- bucket ---------- */
  function applyFill(o, sid, size) {
    if (sid && byId[sid]) { o.pattern = { sid: sid, size: size }; o.fill = byId[sid].avg || '#888888'; }
    else { delete o.pattern; var nf = document.getElementById('optNoFill'); o.fill = (nf && nf.checked) ? 'none' : (document.getElementById('optFill') || { value: '#44ff66' }).value; }
  }
  window.__toolHandlers.bucket = function (pt) {
    if (window.WandTool && window.WandTool.hasSelection()) { window.WandTool.fillAt(pt); return; }   /* an active wand selection limits the fill to that region */
    var i = hitShape(pt);
    if (i < 0) { toast('Click inside a shape to fill it'); return; }
    var o = objects[i];
    if (o.type === 'image') { toast('Images cannot be bucket-filled. Use the Magic Wand to make a cut outline from an image.'); return; }
    if (o.type === 'line') { toast('Lines have no inside to fill'); return; }
    if (o.locked) { toast('That object is locked'); return; }
    if (state.sid && !byId[state.sid]) state.sid = null;
    pushUndo();
    var targets = (o.gid && selIds.indexOf(o.id) >= 0 && selIds.length > 1) ? objects.filter(function (m) { return selIds.indexOf(m.id) >= 0 && m.type !== 'image' && m.type !== 'line' && !m.locked; }) : [o];
    targets.forEach(function (t) { applyFill(t, state.sid, state.size); });
    selectMany([o.id]); refreshLayers(); draw();
    toast(state.sid ? 'Filled with ' + byId[state.sid].name : 'Filled with colour');
  };

  /* ---------- panel ---------- */
  var panel, body;
  function mkPanel() {
    var anchor = document.getElementById('swatches'); if (!anchor) return;
    var host = anchor.closest('.spanel'); if (!host) return;
    panel = document.createElement('div'); panel.className = 'spanel'; panel.id = 'swatchPanel';
    var head = document.createElement('div'); head.className = 'spanel-head'; head.textContent = 'Swatch Library '; var cnt = document.createElement('span'); cnt.style.fontSize = '9px'; cnt.id = 'swCount'; head.appendChild(cnt);
    body = document.createElement('div'); body.className = 'spanel-body'; panel.appendChild(head); panel.appendChild(body);
    host.parentNode.insertBefore(panel, host.nextSibling);
    var fi = document.createElement('input'); fi.type = 'file'; fi.id = 'swFileInput'; fi.multiple = true; fi.accept = 'image/png,image/jpeg,image/gif,image/webp,image/svg+xml,.png,.jpg,.jpeg,.gif,.webp,.svg'; fi.style.display = 'none';
    fi.onchange = function () { var fl = Array.prototype.slice.call(fi.files || []).map(function (f) { return { file: f }; }); fi.value = ''; if (fl.length) addFiles(fl); };
    panel.appendChild(fi);
    var fd = document.createElement('input'); fd.type = 'file'; fd.id = 'swFolderInput'; fd.multiple = true; fd.setAttribute('webkitdirectory', ''); fd.setAttribute('directory', ''); fd.style.display = 'none';
    fd.onchange = function () { var items = folderFiles(fd.files); var n = (fd.files || []).length; fd.value = ''; if (items.length) addFiles(items); else { status(0, [n ? 'no usable images in that folder (png jpg gif webp svg)' : 'folder was empty']); } };
    panel.appendChild(fd);
    panel.addEventListener('dragover', function (e) { if (e.dataTransfer && Array.prototype.indexOf.call(e.dataTransfer.types || [], 'Files') >= 0) { e.preventDefault(); e.stopPropagation(); panel.style.outline = '1px dashed #44ff66'; } });
    panel.addEventListener('dragleave', function () { panel.style.outline = ''; });
    panel.addEventListener('drop', function (e) { panel.style.outline = ''; var fl = e.dataTransfer && e.dataTransfer.files; if (!fl || !fl.length) return; e.preventDefault(); e.stopPropagation(); addFiles(Array.prototype.slice.call(fl).map(function (f) { return { file: f }; })); });
  }
  function selectedPatternObjs() { return objects.filter(function (o) { return selIds.indexOf(o.id) >= 0 && o.pattern; }); }
  function renderPanel() {
    if (!body) return; body.textContent = ''; document.getElementById('swCount').textContent = LIB.length;
    var grid = document.createElement('div'); grid.style.cssText = 'display:grid;grid-template-columns:repeat(4,1fr);gap:6px';
    function tile(label, sid, bg) {
      var t = document.createElement('button'); t.type = 'button'; t.className = 'swTile'; t.title = label; t.setAttribute('aria-label', 'Swatch ' + label); t.dataset.sid = sid || '';
      t.style.cssText = 'aspect-ratio:1;border-radius:6px;cursor:pointer;padding:0;background-size:cover;background-position:center;color:#ddd;font:10px var(--ui);border:2px solid ' + ((state.sid || '') === (sid || '') ? 'var(--portal,#44ff66)' : '#444') + ';' + (bg || '');
      t.onclick = function () { state.sid = sid; renderPanel(); if (typeof tool !== 'undefined' && tool !== 'bucket') setTool('bucket'); updateBucketOpts(); };
      return t;
    }
    var solid = tile('Solid colour (uses the Fill colour)', null, 'background:linear-gradient(135deg,#44ff66,#00c8ff)'); solid.textContent = 'Solid'; grid.appendChild(solid);
    LIB.forEach(function (s) { var t = tile(s.name, s.id, ''); t.style.backgroundImage = 'url("' + s.data.replace(/"/g, '') + '")'; grid.appendChild(t); });
    body.appendChild(grid);
    if (!LIB.length) {
      var m = document.createElement('div'); m.id = 'swEmpty'; m.style.cssText = 'font-size:11px;color:#9a9ab8;margin-top:8px;line-height:1.4';
      m.textContent = 'No swatches yet. Click Add images (or Choose folder) below, or drop image files here.'; body.appendChild(m);
    }
    var bar = document.createElement('div'); bar.style.cssText = 'display:flex;flex-wrap:wrap;gap:6px;margin-top:8px';
    function bt(id, label, title, fn) { var b = document.createElement('button'); b.type = 'button'; b.id = id; b.className = 'hbtn'; b.textContent = label; b.title = title; b.style.cssText = 'padding:5px 9px;font-size:11px'; b.onclick = fn; bar.appendChild(b); return b; }
    bt('btnSwAdd', '+ Add images\u2026', 'Pick one or many image files (png jpg gif webp svg). They are remembered in this browser.', function () { var fi = document.getElementById('swFileInput'); if (fi) fi.click(); });
    bt('btnSwFolder', 'Choose folder\u2026', 'Load every image in a folder (and its sub-folders)', function () { chooseFolder(); });
    var cur = state.sid && byId[state.sid];
    if (cur && cur.user) bt('btnSwRemove', 'Remove \u201C' + cur.name.slice(0, 14) + '\u201D', 'Delete this swatch from the library (shapes already filled keep their colour)', function () { removeSwatch(cur.id); });
    body.appendChild(bar);
    var st = document.createElement('div'); st.id = 'swStatus'; st.style.cssText = 'font-size:10px;margin-top:6px;color:#9a9ab8;line-height:1.35'; body.appendChild(st); showStatus();
    var row = document.createElement('div'); row.className = 'opt-row'; row.style.marginTop = '8px';
    var lb = document.createElement('label'); lb.textContent = 'Tile size'; var rg = document.createElement('input'); rg.type = 'range'; rg.id = 'swSize'; rg.min = '0.1'; rg.max = '8'; rg.step = '0.05'; rg.value = state.size; rg.style.flex = '1';
    var vl = document.createElement('span'); vl.id = 'swSizeV'; vl.style.cssText = 'font:11px var(--mono);min-width:42px'; vl.textContent = (+state.size).toFixed(2) + '"';
    rg.onpointerdown = function () { if (selectedPatternObjs().length) pushUndo(); };
    rg.oninput = function () { state.size = +rg.value; vl.textContent = state.size.toFixed(2) + '"'; var ps = selectedPatternObjs(); if (ps.length) { ps.forEach(function (o) { o.pattern.size = state.size; }); draw(); } };
    row.appendChild(lb); row.appendChild(rg); row.appendChild(vl); body.appendChild(row);
    var hint = document.createElement('div'); hint.style.cssText = 'font-size:10px;color:#9a9ab8;margin-top:6px'; hint.textContent = 'Pick a swatch, then click a shape with the Bucket (B). The slider also resizes the tiles of selected filled shapes. Drop image files onto this panel to add them.'; body.appendChild(hint);
  }

  /* ---------- Bucket tool options ---------- */
  function updateBucketOpts() {
    var old = document.getElementById('subOpts'); if (typeof tool === 'undefined' || tool !== 'bucket') return;
    if (old) old.remove();
    var cont = document.querySelector('.spanel-body'); if (!cont) return;
    var d = document.createElement('div'); d.id = 'subOpts'; d.style.cssText = 'border-top:1px solid var(--bdr);padding-top:8px;margin-top:8px;font-size:11px;color:#c8c8e0;line-height:1.4';
    var h = document.createElement('div'); h.style.cssText = 'font:700 9px var(--ui);text-transform:uppercase;letter-spacing:1.5px;color:var(--portal);margin-bottom:6px'; h.textContent = 'bucket Options'; d.appendChild(h);
    var t = document.createElement('div'); t.id = 'bucketInfo'; t.textContent = 'Fill with: ' + (state.sid && byId[state.sid] ? byId[state.sid].name + ' (tile ' + (+state.size).toFixed(2) + '")' : 'solid colour (see Fill above)') + '. Click inside a shape' + (window.WandTool && window.WandTool.hasSelection() ? ' (a wand selection is active: the fill goes inside the selection only; Esc clears it).' : ', or make a Magic Wand selection first to paint just that part.'); d.appendChild(t);
    cont.appendChild(d);
  }
  if (typeof updateToolOpts === 'function') { var _u = updateToolOpts; updateToolOpts = function (t) { var r = _u.apply(this, arguments); if (t === 'bucket') updateBucketOpts(); return r; }; }

  document.addEventListener('keydown', function (e) {
    if (e.ctrlKey || e.metaKey || e.altKey || e.shiftKey || ['INPUT', 'TEXTAREA', 'SELECT'].indexOf((e.target || {}).tagName) >= 0) return;
    if ((e.key === 'b' || e.key === 'B') && typeof setTool === 'function') setTool('bucket');
  });

  mkPanel(); sortLib(); renderPanel(); var restoreDone = restoreUser();
  window.SwatchLib = { items: function () { return LIB; }, get: function (id) { return byId[id]; }, state: state, svgPattern: svgPattern, applyFill: applyFill, hitShape: hitShape, addFiles: addFiles, removeSwatch: removeSwatch, chooseFolder: chooseFolder, ready: function () { return restoreDone; }, select: function (id) { state.sid = id; renderPanel(); } };
})();
